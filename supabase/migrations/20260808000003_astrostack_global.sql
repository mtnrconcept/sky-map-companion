--Metàjourastro_objects+astro_contributionsaprèsunuploadqualifié
CREATEORREPLACEFUNCTIONupdate_object_stats_on_upload()
RETURNSTRIGGERAS$$
BEGIN
--Miseàjourdescompteurssurl'objet
IFNEW.object_idISNOTNULLANDNEW.rejected=falseTHEN
IFNEW.frame_type='light'THEN
UPDATEpublic.astro_objects
SETtotal_lights=total_lights+1,
total_exposure_hours=total_exposure_hours+COALESCE(NEW.exposure_s,0)/3600.0
WHEREid=NEW.object_id;
ELSIFNEW.frame_type='dark'THEN
UPDATEpublic.astro_objectsSETtotal_darks=total_darks+1WHEREid=NEW.object_id;
ELSIFNEW.frame_type='flat'THEN
UPDATEpublic.astro_objectsSETtotal_flats=total_flats+1WHEREid=NEW.object_id;
ELSIFNEW.frame_type='bias'THEN
UPDATEpublic.astro_objectsSETtotal_bias=total_bias+1WHEREid=NEW.object_id;
ENDIF;

--Upsertcontributions
INSERTINTOpublic.astro_contributions(user_id,object_id,
lights_count,darks_count,flats_count,bias_count,
total_exposure_hours,last_contribution_at)
VALUES(
NEW.user_id,NEW.object_id,
CASEWHENNEW.frame_type='light'THEN1ELSE0END,
CASEWHENNEW.frame_type='dark'THEN1ELSE0END,
CASEWHENNEW.frame_type='flat'THEN1ELSE0END,
CASEWHENNEW.frame_type='bias'THEN1ELSE0END,
CASEWHENNEW.frame_type='light'THENCOALESCE(NEW.exposure_s,0)/3600.0ELSE0END,
now()
)
ONCONFLICT(user_id,object_id)DOUPDATESET
lights_count=astro_contributions.lights_count+EXCLUDED.lights_count,
darks_count=astro_contributions.darks_count+EXCLUDED.darks_count,
flats_count=astro_contributions.flats_count+EXCLUDED.flats_count,
bias_count=astro_contributions.bias_count+EXCLUDED.bias_count,
total_exposure_hours=astro_contributions.total_exposure_hours+EXCLUDED.total_exposure_hours,
last_contribution_at=now();

--Metàjourlecompteurdecontributeursuniques
UPDATEpublic.astro_objects
SETtotal_contributors=(
SELECTCOUNT(DISTINCTuser_id)
FROMpublic.astro_uploads
WHEREobject_id=NEW.object_idANDrejected=false
)
WHEREid=NEW.object_id;
ENDIF;
RETURNNULL;
END;
$$LANGUAGEplpgsql;

CREATETRIGGERtrigger_update_object_stats
AFTERINSERTONpublic.astro_uploads
FOREACHROWEXECUTEFUNCTIONupdate_object_stats_on_upload();

