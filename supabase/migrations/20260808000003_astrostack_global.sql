--RPC:recherched'objets+statspourcontribution
--============================================================
CREATEORREPLACEFUNCTIONsearch_astro_objects(
querytextDEFAULT'',
object_typetextDEFAULTNULL,
min_contributorsintegerDEFAULT0,
limit_countintegerDEFAULT20
)
RETURNSSETOFpublic.astro_objectsAS$$
BEGIN
RETURNQUERY
SELECT*FROMpublic.astro_objects
WHERE
(query=''OR
idILIKE'%'||query||'%'OR
common_nameILIKE'%'||query||'%'
)
AND(object_typeISNULLORtype=object_type)
ANDtotal_contributors>=min_contributors
ORDERBYtotal_lightsDESC,idASC
LIMITlimit_count;
END;
$$LANGUAGEplpgsqlSECURITYDEFINER;

