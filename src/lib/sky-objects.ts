exportfunctionfindSkyObject(key:string,date:Date):SkyObject|null{
if(key.startsWith("dso:")){
consto=deepSky.find((d)=>d.id===key.slice(4));
returno?dsoToSkyObject(o):null;
}
if(key.startsWith("star:")){
returnstarToSkyObject(Number.parseInt(key.slice(5),10));
}
returnsolarSystemObjects(date).find((o)=>o.key===key)??null;
}

