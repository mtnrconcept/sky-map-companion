exportfunctiondsoToSkyObject(o:DeepSkyObject):SkyObject{
return{
key:`dso:${o.id}`,
name:o.name,
subtitle:`${o.id}${o.designation&&o.designation!==o.id?`·${o.designation}`:""}·${TYPE_LABELS[o.type]??"Objet"}`,
kind:"dso",
ra:o.ra,
dec:o.dec,
mag:o.mag,
constellation:constellationNames[o.con]??o.con,
instrument:o.instrument,
description:o.description,
sizeArcmin:o.size,
photoQuery:`${o.id}${o.designation&&o.designation!==o.id?o.designation:""}astronomy`,
photoQueries:[
`${o.id}${o.designation&&o.designation!==o.id?o.designation:""}`.trim(),
o.designation&&o.designation!==o.id?o.designation:`${o.id}object`,
`${o.id}${TYPE_EN[o.type]??"deepskyobject"}`,
`${o.id}telescopeimage`,
],
};

}

exportfunctionstarToSkyObject(index:number):SkyObject|null{
consts=stars[index];
if(!s)returnnull;
return{
key:`star:${index}`,
name:s.n||`${s.b||"Étoile"}${constellationNames[s.c]??s.c}`,
subtitle:`Étoile·magnitude${s.m.toFixed(2)}`,
kind:"star",
ra:s.r,
dec:s.d,
mag:s.m,
constellation:constellationNames[s.c]??s.c,
instrument:s.m<=6?"oeil-nu":"jumelles",
description:s.n
?`${s.n}estl'unedesétoilesnomméesduciel,danslaconstellation${constellationNames[s.c]??s.c}.`
:`Étoiledelaconstellation${constellationNames[s.c]??s.c}.`,
sizeArcmin:0,
photoQuery:`${s.n||`${s.b??""}${s.c}`}starastronomy`,
photoQueries:[
`${s.n||`${s.b??""}${s.c}`}star`,
`${s.n||s.b}${s.c}constellation`,
`${s.c}constellationnightsky`,
],
};

}

