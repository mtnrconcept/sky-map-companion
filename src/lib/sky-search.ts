/**Scored'intérêtpourlasélection«cesoir».*/
exportfunctiontonightHighlights(
date:Date,
pos:GeoPosition,
limit=12,
):SearchResult[]{
constresults=searchSky(
{...DEFAULT_FILTERS,onlyVisible:true,maxMagnitude:10},
date,
pos,
);
returnresults
.map((r)=>({
r,
score:r.vis.altitude/90-(r.mag??8)/20+(r.family==="planete"?0.6:0),
}))
.sort((a,b)=>b.score-a.score)
.slice(0,limit)
.map((x)=>x.r);
}
