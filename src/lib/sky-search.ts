exportfunctioncomputeVisibility(
o:{ra:number;dec:number},
date:Date,
pos:GeoPosition,
):Visibility{
constlst=localSiderealTime(date,pos.longitude);
consthz=equatorialToHorizontal({ra:o.ra,dec:o.dec},lst,pos.latitude);
constrs=riseSetTimes({ra:o.ra,dec:o.dec},date,pos);
return{
altitude:hz.alt,
azimuth:hz.az,
direction:cardinalName(hz.az),
visible:hz.alt>0,
rise:rs.rise,
set:rs.set,
transit:rs.transit,
maxAltitude:rs.maxAltitude,
};
}

